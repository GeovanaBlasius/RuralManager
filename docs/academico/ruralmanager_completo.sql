CREATE SCHEMA RURALMANAGER;
USE RURALMANAGER;

CREATE TABLE PRODUTOR(
PRD_CPF CHAR(11) NOT NULL,
PRD_NOME VARCHAR(120) NOT NULL,
PRD_TELEFONE VARCHAR(20) NOT NULL,
PRD_ENDERECO VARCHAR(160),
PRD_CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
PRIMARY KEY (PRD_CPF),
CHECK (PRD_CPF REGEXP '^[0-9]{11}$')
);

CREATE TABLE PRODUTO(
PRO_CODE SMALLINT NOT NULL,
PRO_NOME VARCHAR(60) NOT NULL,
PRIMARY KEY (PRO_CODE),
UNIQUE (PRO_NOME)
);

CREATE TABLE SAFRA (
    SAF_CODE INTEGER NOT NULL,
    PRD_CPF CHAR(11) NOT NULL,
    SAF_ANO_INICIO SMALLINT NOT NULL,
    SAF_ANO_FIM SMALLINT NOT NULL,
    SAF_DESCRICAO VARCHAR(100),
    PRIMARY KEY (SAF_CODE),
    FOREIGN KEY (PRD_CPF) REFERENCES PRODUTOR (PRD_CPF),
    UNIQUE (PRD_CPF, SAF_ANO_INICIO, SAF_ANO_FIM),
    CHECK (SAF_ANO_INICIO >= 1900),
    CHECK (SAF_ANO_FIM >= SAF_ANO_INICIO),
    CHECK (SAF_ANO_FIM <= SAF_ANO_INICIO + 1)
);
CREATE TABLE CULTURA(
CUL_CODE INTEGER NOT NULL,
SAF_CODE INTEGER NOT NULL,
PRO_CODE SMALLINT NOT NULL,
CUL_VARIEDADE VARCHAR(60) NOT NULL,
CUL_AREA_HA DECIMAL(10,2) NOT NULL,
CUL_DATA_PLANTIO DATE NOT NULL,
PRIMARY KEY (CUL_CODE),
FOREIGN KEY (SAF_CODE) REFERENCES SAFRA(SAF_CODE),
FOREIGN KEY (PRO_CODE) REFERENCES PRODUTO(PRO_CODE),
UNIQUE (SAF_CODE, PRO_CODE, CUL_VARIEDADE),
UNIQUE (SAF_CODE, CUL_CODE),
CHECK (CUL_AREA_HA > 0)
);

CREATE TABLE UNIDADE_MEDIDA(
UNI_CODE SMALLINT NOT NULL,
UNI_NOME VARCHAR(40) NOT NULL,
UNI_SIGLA VARCHAR(10) NOT NULL,
UNI_FATOR_KG DECIMAL(10,3),
PRIMARY KEY (UNI_CODE),
UNIQUE (UNI_NOME),
UNIQUE (UNI_SIGLA),
CHECK (UNI_FATOR_KG IS NULL OR UNI_FATOR_KG > 0)
);

CREATE TABLE CATEGORIA(
CAT_CODE SMALLINT NOT NULL,
CAT_NOME VARCHAR(40) NOT NULL,
PRIMARY KEY (CAT_CODE),
UNIQUE (CAT_NOME)
);

CREATE TABLE COLHEITA(
COL_CODE INTEGER NOT NULL,
CUL_CODE INTEGER NOT NULL,
UNI_CODE SMALLINT NOT NULL,
COL_QUANTIDADE DECIMAL(12,2) NOT NULL,
COL_DATA DATE NOT NULL,
PRIMARY KEY (COL_CODE),
FOREIGN KEY (CUL_CODE) REFERENCES CULTURA(CUL_CODE),
FOREIGN KEY (UNI_CODE) REFERENCES UNIDADE_MEDIDA(UNI_CODE),
UNIQUE (CUL_CODE, COL_CODE),
CHECK (COL_QUANTIDADE > 0)
);

CREATE TABLE GASTO(
GAS_CODE INTEGER NOT NULL,
SAF_CODE INTEGER NOT NULL,
CUL_CODE INTEGER,
COL_CODE INTEGER,
CAT_CODE SMALLINT NOT NULL,
GAS_DESCRICAO VARCHAR(160) NOT NULL,
GAS_VALOR DECIMAL(12,2) NOT NULL,
GAS_DATA DATE NOT NULL,
PRIMARY KEY (GAS_CODE),
FOREIGN KEY (SAF_CODE) REFERENCES SAFRA(SAF_CODE),
FOREIGN KEY (SAF_CODE, CUL_CODE) REFERENCES CULTURA(SAF_CODE, CUL_CODE),
FOREIGN KEY (CUL_CODE, COL_CODE) REFERENCES COLHEITA(CUL_CODE, COL_CODE),
FOREIGN KEY (CAT_CODE) REFERENCES CATEGORIA(CAT_CODE),
CHECK (GAS_VALOR > 0)
);

CREATE TABLE DESTINO(
DES_CODE SMALLINT NOT NULL,
DES_NOME VARCHAR(40) NOT NULL,
PRIMARY KEY (DES_CODE),
UNIQUE (DES_NOME)
);

CREATE TABLE SAIDA(
SAI_CODE INTEGER NOT NULL,
COL_CODE INTEGER NOT NULL,
DES_CODE SMALLINT NOT NULL,
SAI_QUANTIDADE DECIMAL(12,2) NOT NULL,
SAI_DATA DATE NOT NULL,
SAI_OBSERVACAO VARCHAR(160),
PRIMARY KEY (SAI_CODE),
FOREIGN KEY (COL_CODE) REFERENCES COLHEITA(COL_CODE),
FOREIGN KEY (DES_CODE) REFERENCES DESTINO(DES_CODE),
CHECK (SAI_QUANTIDADE > 0)
);

CREATE TABLE CLIENTE(
CLI_CODE INTEGER NOT NULL,
CLI_NOME VARCHAR(120) NOT NULL,
CLI_CPF_CNPJ VARCHAR(14) NOT NULL,
CLI_TELEFONE VARCHAR(20) NOT NULL,
CLI_ENDERECO VARCHAR(160) NOT NULL,
PRIMARY KEY (CLI_CODE),
UNIQUE (CLI_CPF_CNPJ)
);

CREATE TABLE FATURA(
FAT_CODE INTEGER NOT NULL,
CLI_CODE INTEGER NOT NULL,
FAT_DATA_COMPRA DATE NOT NULL,
PRIMARY KEY (FAT_CODE),
FOREIGN KEY (CLI_CODE) REFERENCES CLIENTE(CLI_CODE)
);

CREATE TABLE ITEM_FATURA(
FAT_CODE INTEGER NOT NULL,
COL_CODE INTEGER NOT NULL,
ITE_QUANTIDADE DECIMAL(12,2) NOT NULL,
ITE_PRECO_UNITARIO DECIMAL(12,2) NOT NULL,
PRIMARY KEY (FAT_CODE, COL_CODE),
FOREIGN KEY (FAT_CODE) REFERENCES FATURA(FAT_CODE),
FOREIGN KEY (COL_CODE) REFERENCES COLHEITA(COL_CODE),
CHECK (ITE_QUANTIDADE > 0),
CHECK (ITE_PRECO_UNITARIO > 0)
);

