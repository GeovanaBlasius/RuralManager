-- Comercializacao da producao.

-- Os clientes sao proprios de cada produtor: quem compra de um nao e
-- informacao do vizinho. Por isso a unicidade do documento e por produtor,
-- e nao global.
CREATE TABLE cliente (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    produtor_id BIGINT       NOT NULL,
    nome        VARCHAR(120) NOT NULL,
    cpf_cnpj    VARCHAR(14)  NOT NULL,
    telefone    VARCHAR(20)  NULL,
    endereco    VARCHAR(160) NULL,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL,
    CONSTRAINT pk_cliente          PRIMARY KEY (id),
    CONSTRAINT uk_cliente_documento UNIQUE (produtor_id, cpf_cnpj),
    CONSTRAINT fk_cliente_produtor FOREIGN KEY (produtor_id) REFERENCES produtor (id),
    CONSTRAINT ck_cliente_documento CHECK (cpf_cnpj ~ '^[0-9]{11}$' OR cpf_cnpj ~ '^[0-9]{14}$')
);

CREATE INDEX ix_cliente_produtor ON cliente (produtor_id);

CREATE TABLE fatura (
    id          BIGINT   GENERATED BY DEFAULT AS IDENTITY,
    cliente_id  BIGINT   NOT NULL,
    data_compra DATE     NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP NOT NULL,
    CONSTRAINT pk_fatura         PRIMARY KEY (id),
    CONSTRAINT fk_fatura_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

CREATE INDEX ix_fatura_cliente ON fatura (cliente_id);

-- Cada item liga uma fatura a uma colheita. E o que viabiliza a venda
-- parcelada: parte da colheita hoje, parte depois, a compradores e por
-- precos diferentes. O preco e por unidade da medida da colheita de origem.
CREATE TABLE item_fatura (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    fatura_id      BIGINT        NOT NULL,
    colheita_id    BIGINT        NOT NULL,
    quantidade     NUMERIC(12,2) NOT NULL,
    preco_unitario NUMERIC(12,2) NOT NULL,
    created_at     TIMESTAMP      NOT NULL,
    updated_at     TIMESTAMP      NOT NULL,
    CONSTRAINT pk_item_fatura       PRIMARY KEY (id),
    CONSTRAINT uk_item_fatura_unico UNIQUE (fatura_id, colheita_id),
    CONSTRAINT fk_item_fatura       FOREIGN KEY (fatura_id)   REFERENCES fatura (id),
    CONSTRAINT fk_item_colheita     FOREIGN KEY (colheita_id) REFERENCES colheita (id),
    CONSTRAINT ck_item_quantidade   CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco        CHECK (preco_unitario > 0)
);

CREATE INDEX ix_item_fatura_colheita ON item_fatura (colheita_id);
