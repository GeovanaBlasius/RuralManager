-- Despesas do periodo e saidas de producao que nao configuram venda.

-- Todo gasto pertence a uma safra. A cultura e a colheita sao opcionais:
-- custos gerais, como diesel, salario e arrendamento, nao pertencem a
-- lavoura nenhuma e seriam perdidos se o vinculo fosse obrigatorio.
--
-- A coerencia entre os tres vinculos -- a lavoura ser da mesma safra e a
-- colheita ser daquela lavoura -- e validada na camada de servico, e nao
-- por chave estrangeira composta, que tornaria o mapeamento objeto
-- relacional inviavel por sobrepor colunas em mais de um relacionamento.
CREATE TABLE gasto (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    safra_id           BIGINT        NOT NULL,
    cultura_id         BIGINT        NULL,
    colheita_id        BIGINT        NULL,
    categoria_gasto_id BIGINT        NOT NULL,
    descricao          VARCHAR(160)  NOT NULL,
    valor              NUMERIC(12,2) NOT NULL,
    data_gasto         DATE          NOT NULL,
    created_at         TIMESTAMP      NOT NULL,
    updated_at         TIMESTAMP      NOT NULL,
    CONSTRAINT pk_gasto           PRIMARY KEY (id),
    CONSTRAINT fk_gasto_safra     FOREIGN KEY (safra_id)           REFERENCES safra (id),
    CONSTRAINT fk_gasto_cultura   FOREIGN KEY (cultura_id)         REFERENCES cultura (id),
    CONSTRAINT fk_gasto_colheita  FOREIGN KEY (colheita_id)        REFERENCES colheita (id),
    CONSTRAINT fk_gasto_categoria FOREIGN KEY (categoria_gasto_id) REFERENCES categoria_gasto (id),
    CONSTRAINT ck_gasto_valor     CHECK (valor > 0)
);

CREATE INDEX ix_gasto_safra   ON gasto (safra_id);
CREATE INDEX ix_gasto_cultura ON gasto (cultura_id);

-- Producao que deixa o estoque sem passar por venda: consumo proprio,
-- semente guardada, alimentacao animal, parceria, troca por insumos,
-- perda posterior a colheita e doacao.
CREATE TABLE saida (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    colheita_id BIGINT        NOT NULL,
    destino_id  BIGINT        NOT NULL,
    quantidade  NUMERIC(12,2) NOT NULL,
    data_saida  DATE          NOT NULL,
    observacao  VARCHAR(160)  NULL,
    created_at  TIMESTAMP      NOT NULL,
    updated_at  TIMESTAMP      NOT NULL,
    CONSTRAINT pk_saida          PRIMARY KEY (id),
    CONSTRAINT fk_saida_colheita FOREIGN KEY (colheita_id) REFERENCES colheita (id),
    CONSTRAINT fk_saida_destino  FOREIGN KEY (destino_id)  REFERENCES destino (id),
    CONSTRAINT ck_saida_qtd      CHECK (quantidade > 0)
);

CREATE INDEX ix_saida_colheita ON saida (colheita_id);
