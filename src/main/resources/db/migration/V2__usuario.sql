-- Usuario: autenticacao e vinculo com o produtor dono dos dados.
--
-- O usuario e quem acessa o sistema; o produtor e a entidade de dominio.
-- Um produtor pode ter varios usuarios (o proprio, conjuge, filho, contador)
-- e um usuario pertence a um unico produtor. O perfil ADMIN nao tem produtor
-- vinculado, pois atende a operacao do sistema e nao a de uma propriedade.

CREATE TABLE usuario (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    produtor_id   BIGINT       NULL,
    nome          VARCHAR(120) NOT NULL,
    email         VARCHAR(160) NOT NULL,
    senha_hash    VARCHAR(100) NOT NULL,
    perfil        VARCHAR(20)  NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    ultimo_acesso TIMESTAMP     NULL,
    created_at    TIMESTAMP     NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    CONSTRAINT pk_usuario       PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT fk_usuario_produtor FOREIGN KEY (produtor_id)
        REFERENCES produtor (id),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN','PRODUTOR','OPERADOR')),
    CONSTRAINT ck_usuario_vinculo CHECK (
        (perfil =  'ADMIN' AND produtor_id IS NULL) OR
        (perfil <> 'ADMIN' AND produtor_id IS NOT NULL)
    )
);

CREATE INDEX ix_usuario_produtor ON usuario (produtor_id);
