-- Chamado de suporte: o usuario relata um problema para a equipe melhorar o sistema.
--
-- Vinculado ao usuario (nao ao produtor): ADMIN nao tem produtor, mas tambem
-- pode querer registrar algo, e cada usuario ve so os proprios chamados.

CREATE TABLE chamado_suporte (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    usuario_id BIGINT        NOT NULL,
    titulo     VARCHAR(120)  NOT NULL,
    descricao  VARCHAR(2000) NOT NULL,
    status     VARCHAR(20)   NOT NULL DEFAULT 'ABERTO',
    created_at TIMESTAMP     NOT NULL,
    updated_at TIMESTAMP     NOT NULL,
    CONSTRAINT pk_chamado_suporte PRIMARY KEY (id),
    CONSTRAINT fk_chamado_suporte_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuario (id),
    CONSTRAINT ck_chamado_suporte_status CHECK (status IN ('ABERTO','RESOLVIDO'))
);

CREATE INDEX ix_chamado_suporte_usuario ON chamado_suporte (usuario_id);

ALTER TABLE chamado_suporte ENABLE ROW LEVEL SECURITY;
