-- Nucleo produtivo: o periodo, a lavoura e a producao retirada dela.

-- A safra atravessa dois anos civis, com plantio no segundo semestre de um
-- ano e colheita no primeiro do seguinte, por isso o par de anos.
CREATE TABLE safra (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    produtor_id BIGINT       NOT NULL,
    ano_inicio  SMALLINT     NOT NULL,
    ano_fim     SMALLINT     NOT NULL,
    descricao   VARCHAR(255) NULL,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL,
    CONSTRAINT pk_safra          PRIMARY KEY (id),
    CONSTRAINT uk_safra_periodo  UNIQUE (produtor_id, ano_inicio, ano_fim),
    CONSTRAINT fk_safra_produtor FOREIGN KEY (produtor_id) REFERENCES produtor (id),
    CONSTRAINT ck_safra_ano_inicio CHECK (ano_inicio >= 1900),
    CONSTRAINT ck_safra_ano_fim    CHECK (ano_fim >= ano_inicio AND ano_fim <= ano_inicio + 1)
);

-- Cultura e a lavoura efetivamente plantada: a ocorrencia de um produto
-- dentro de uma safra, com os atributos que mudam a cada plantio.
CREATE TABLE cultura (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    safra_id     BIGINT        NOT NULL,
    produto_id   BIGINT        NOT NULL,
    variedade    VARCHAR(60)   NOT NULL,
    area_ha      NUMERIC(10,2) NOT NULL,
    data_plantio DATE          NOT NULL,
    created_at   TIMESTAMP      NOT NULL,
    updated_at   TIMESTAMP      NOT NULL,
    CONSTRAINT pk_cultura         PRIMARY KEY (id),
    CONSTRAINT uk_cultura_natural UNIQUE (safra_id, produto_id, variedade),
    CONSTRAINT fk_cultura_safra   FOREIGN KEY (safra_id)   REFERENCES safra (id),
    CONSTRAINT fk_cultura_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_cultura_area    CHECK (area_ha > 0)
);

CREATE INDEX ix_cultura_safra ON cultura (safra_id);

-- Producao fisica retirada da lavoura. Nao guarda preco nem indicacao de
-- venda: a mesma colheita pode ser comercializada em partes, para
-- compradores diferentes e por valores diferentes.
CREATE TABLE colheita (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    cultura_id        BIGINT        NOT NULL,
    unidade_medida_id BIGINT        NOT NULL,
    quantidade        NUMERIC(12,2) NOT NULL,
    data_colheita     DATE          NOT NULL,
    created_at        TIMESTAMP      NOT NULL,
    updated_at        TIMESTAMP      NOT NULL,
    CONSTRAINT pk_colheita         PRIMARY KEY (id),
    CONSTRAINT fk_colheita_cultura FOREIGN KEY (cultura_id)        REFERENCES cultura (id),
    CONSTRAINT fk_colheita_unidade FOREIGN KEY (unidade_medida_id) REFERENCES unidade_medida (id),
    CONSTRAINT ck_colheita_qtd     CHECK (quantidade > 0)
);

CREATE INDEX ix_colheita_cultura ON colheita (cultura_id);
