-- Catalogos compartilhados por todos os produtores.

CREATE TABLE produto (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(60) NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    CONSTRAINT pk_produto      PRIMARY KEY (id),
    CONSTRAINT uk_produto_nome UNIQUE (nome)
);

-- fator_kg nulo nas unidades sem peso definido, como unidade avulsa e duzia.
-- E o que permite comparar produtividade entre lavouras medidas de formas
-- diferentes, convertendo tudo para uma base comum.
CREATE TABLE unidade_medida (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(40)   NOT NULL,
    sigla      VARCHAR(10)   NOT NULL,
    fator_kg   NUMERIC(12,4) NULL,
    created_at TIMESTAMP      NOT NULL,
    updated_at TIMESTAMP      NOT NULL,
    CONSTRAINT pk_unidade_medida       PRIMARY KEY (id),
    CONSTRAINT uk_unidade_medida_nome  UNIQUE (nome),
    CONSTRAINT uk_unidade_medida_sigla UNIQUE (sigla),
    CONSTRAINT ck_unidade_medida_fator CHECK (fator_kg IS NULL OR fator_kg > 0)
);

CREATE TABLE categoria_gasto (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(40) NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    CONSTRAINT pk_categoria_gasto      PRIMARY KEY (id),
    CONSTRAINT uk_categoria_gasto_nome UNIQUE (nome)
);

-- Destinos da producao que nao se convertem em venda.
CREATE TABLE destino (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(40) NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    CONSTRAINT pk_destino      PRIMARY KEY (id),
    CONSTRAINT uk_destino_nome UNIQUE (nome)
);
